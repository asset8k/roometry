import definitions from '../../data/core-furniture.generated.json'

export type FurniturePoint = readonly [number, number, number]
export type FurnitureMaterial = 'primary' | 'primary_dark' | 'primary_metal' | 'wood' | 'metal' | 'linen' | 'inset'
  | 'screen' | 'rubber' | 'light' | 'indicator' | 'glass'
  | 'primary_ceramic' | 'chrome' | 'enamel' | 'clear_glass'
  | 'foliage' | 'foliage_dark' | 'soil' | 'paper' | 'mirror'
export type AssetPlacement = 'floor' | 'surface' | 'wall' | 'ceiling'
export type AssetCategory = 'furniture' | 'electronics' | 'lighting' | 'climate' | 'kitchen' | 'bathroom' | 'utility' | 'decor'
export interface FurniturePart {
  name: string
  size: FurniturePoint
  at: FurniturePoint
  material: FurnitureMaterial
  shape: 'box' | 'rounded_box' | 'cylinder' | 'tube' | 'ellipsoid' | 'torus' | 'basin' | 'frustum' | 'pleated_panel' | 'arched_panel'
  radius: number
  collision: boolean
  top_scale: number
  bottom_scale: number
  wall_thickness: number
  rotation: FurniturePoint
  placements: readonly AssetPlacement[]
  profile: readonly (readonly [number, number])[]
}
export interface FurnitureSurface {
  name: string
  part: string
  y: number
  x_min: number
  x_max: number
  z_min: number
  z_max: number
  purpose: 'objects' | 'seating' | 'sleeping'
}
export interface FurnitureAsset {
  asset_id: string
  object_type: string
  label: string
  dimensions_m: FurniturePoint
  color: string
  category: AssetCategory
  placements: readonly AssetPlacement[]
  placement_dimensions_m: Readonly<Record<AssetPlacement, FurniturePoint | undefined>>
  placement_anchors: Readonly<Record<string, { at: FurniturePoint; normal: FurniturePoint }>>
  parts: readonly FurniturePart[]
  surfaces: readonly FurnitureSurface[]
}

// Generated by scripts/export_scene_contract.py from the Python catalog.
// Importing an array avoids magic keys on ordinary JavaScript objects.
export const FURNITURE_CATALOG = definitions as unknown as readonly FurnitureAsset[]
const byId = new Map(FURNITURE_CATALOG.map(asset => [asset.asset_id, asset]))

export function getFurnitureAsset(assetId: string): FurnitureAsset | undefined {
  return byId.get(assetId)
}
